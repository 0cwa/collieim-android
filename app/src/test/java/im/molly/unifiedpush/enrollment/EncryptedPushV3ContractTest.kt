class EncryptedPushV3ContractTest {
  private val mapper = ObjectMapper()
  private fun resource(path: String) = javaClass.getResourceAsStream(path)!!.readBytes()
  private fun json(path: String): JsonNode = mapper.readTree(resource(path))

  @Test
  fun `v2 and v3 copied contract inventories exactly match their manifests`() {
    assertManifest("/colliesocket-contract-v2")
    assertManifest("/colliesocket-contract-v3")
  }

  private fun assertManifest(resourceDir: String) {
    val dir = File(javaClass.getResource(resourceDir)!!.toURI())
    val manifest = mapper.readTree(File(dir, "copy-manifest.json"))
    val entries = manifest["files"].associate { it["path"].asText() to it["sha256"].asText() }
    assertEquals("$resourceDir manifest entry count", if (resourceDir.endsWith("v3")) 42 else 10, entries.size)
    val actualPaths = dir.walkTopDown()
      .filter { it.isFile && it.name != "PIN.txt" && it.name != "copy-manifest.json" }
      .map { it.relativeTo(dir).path.replace(File.separatorChar, '/') }
      .toSet()

    val missing = entries.keys - actualPaths
    val unlisted = actualPaths - entries.keys
    assertTrue("missing manifest artifacts for $resourceDir: ${missing.sorted()}", missing.isEmpty())
    assertTrue("unlisted copied artifacts for $resourceDir: ${unlisted.sorted()}", unlisted.isEmpty())
    assertTrue("generated bytecode must not be copied", actualPaths.none { it.endsWith(".pyc") || it.contains("__pycache__") })
    val expectedPin = if (resourceDir.endsWith("v3")) EnrollmentFile.V3_CONTRACT_COMMIT else EnrollmentFile.V2_CONTRACT_COMMIT
    assertTrue("$resourceDir/PIN.txt must record the pinned source revision", File(dir, "PIN.txt").readText().contains(expectedPin))
    for ((path, expected) in entries) {
      val file = File(dir, path)
      assertTrue("missing manifest artifact: $path", file.isFile)
      val actual = MessageDigest.getInstance("SHA-256").digest(file.readBytes()).joinToString("") { "%02x".format(it) }
      assertEquals("$resourceDir/$path", expected, actual)
    }
  }

  @Test
  fun `v2 enrollment bytes retain the frozen schema and v3 matches the exact fixture`() {
    fun input(sequence: Long?, requestId: String = "22222222-2222-4222-8222-222222222222") = EnrollmentFile.Input(
      requestId = requestId,
      accountId = "aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa",
      deviceId = 2,
      password = "SYNTHETIC-NOT-A-SIGNAL-CREDENTIAL",
      endpoint = "https://push.example.invalid/synthetic-endpoint",
      p256dh = "BCVxsr7N_eNgVRqvHtD0zTZsEc6-VV-JvLexhqUzORcxaOzi6-AYWXvTBHm4bjyPjs7Vd8pZGH6SRpkNtoIAiw4",
      auth = "BTBZMqHH6r4Tts7J_aSIgg",
      instance = "fixture-instance",
      epoch = 1,
      controlKey = "AAECAwQFBgcICQoLDA0ODxAREhMUFRYXGBkaGxwdHh8",
      importSequence = sequence,
    )

    val v2 = mapper.readTree(EnrollmentFile.render(input(null)))
    assertEquals(json("/colliesocket-contract-v2/fixtures/enrollment-keyed.json"), v2)
    assertNull(v2["import_seq"])

    val v3 = mapper.readTree(EnrollmentFile.render(input(1)))
    assertEquals(json("/colliesocket-contract-v3/fixtures/enrollment-keyed-v3.json"), v3)

    val legacy = json("/colliesocket-contract-v2/fixtures/enrollment-keyed.json")
    val adoption = json("/colliesocket-contract-v3/fixtures/enrollment-first-v3-adoption-v3.json")
    assertEquals(legacy["account_id"], adoption["account_id"])
    assertEquals(legacy["device_id"], adoption["device_id"])
    assertEquals(legacy["password"], adoption["password"])
    assertEquals(legacy["control_key"], adoption["control_key"])
    for (field in listOf("endpoint", "p256dh", "auth", "instance", "subscription_epoch", "encryption_required", "capabilities")) {
      assertEquals("adoption preserves subscription.$field", legacy["subscription"][field], adoption["subscription"][field])
    }
    assertEquals(mapper.readTree(EnrollmentFile.render(input(1, "33333333-3333-4333-8333-333333333333"))), adoption)
    assertEquals("request identity is fresh", "33333333-3333-4333-8333-333333333333", adoption["request_id"].asText())
    assertEquals(1L, adoption["import_seq"].asLong())
    assertEquals("[1,2]", legacy["subscription"]["supported_event_versions"].toString())
    assertEquals("[1,2,3]", adoption["subscription"]["supported_event_versions"].toString())
  }

  @Test
  fun `v3 event fixtures parse and schema-invalid identities are rejected`() {
    val now = 1800000000L
    val eventPaths = listOf(
      "event-enrollment-imported-v3.json", "event-first-v3-adoption-v3.json", "event-independent-account-b-v3.json",
      "event-subscription-updated-v3.json", "event-test-v3.json", "event-wake-v3.json",
    )
    for (path in eventPaths) {
      val bytes = resource("/colliesocket-contract-v3/fixtures/$path")
      assertFalse("account identity is local context, not an event field", mapper.readTree(bytes).has("account_id"))
      assertNotNull(path, EncryptedPush.parse(bytes, now, setOf(3)))
      assertNull("strict v1/v2 parser must reject v3 extension fields", EncryptedPush.parse(bytes, now, setOf(1, 2)))
    }

    for (path in listOf("event-missing-import-id-v3.json", "event-noncanonical-key-id-v3.json")) {
      assertNull(path, EncryptedPush.parse(resource("/colliesocket-contract-v3/fixtures/$path"), now, setOf(3)))
    }

    val eventWithSequence = mapper.readTree(resource("/colliesocket-contract-v3/fixtures/event-first-v3-adoption-v3.json"))
      .deepCopy<com.fasterxml.jackson.databind.node.ObjectNode>()
      .put("import_seq", 1)
    assertNull("import_seq is never part of a v3 event", EncryptedPush.parse(mapper.writeValueAsBytes(eventWithSequence), now, setOf(3)))
  }

  @Test
  fun `canonical first v3 adoption vectors bind intent before same key and reject mutations`() {
    val cases = json("/colliesocket-contract-v3/fixtures/first-v3-adoption-cases-v3.json")
    val sameKeyPhoneCase = cases["phone_candidate_cases"].first { it["id"].asText() == "same-key-adoption-binds-import-intent" }
    assertEquals(listOf("import_id", "key_id"), sameKeyPhoneCase["lookup_order"].map { it.asText() })
    assertEquals(sameKeyPhoneCase["active_key_id"], sameKeyPhoneCase["candidate_key_id"])
    assertEquals("bind_candidate_sequence_and_intent", sameKeyPhoneCase["expected"].asText())

    val liveContextCase = cases["phone_candidate_cases"].first { it["id"].asText() == "receiver-binds-to-current-live-context" }
    assertEquals(false, liveContextCase["event_contains_account_id"].asBoolean())
    assertEquals("live_signal_store_aci_device_and_current_instance", liveContextCase["binding_source"].asText())
    assertEquals(true, liveContextCase["both_active_v3_and_candidates_checked"].asBoolean())
    assertEquals(false, liveContextCase["stored_export_context_sufficient"].asBoolean())
    assertEquals("no_promotion", liveContextCase["expected"].asText())
    assertEquals("aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa", liveContextCase["candidate_registration_context"]["account_id"].asText())
    assertEquals("bbbbbbbb-bbbb-4bbb-8bbb-bbbbbbbbbbbb", liveContextCase["current_live_registration_context"]["account_id"].asText())

    val mutations = cases["rejected_adoption_mutations"].associateBy { it["id"].asText() }
    val requiredRejections = setOf(
      "adoption-changes-endpoint", "adoption-changes-control-key", "adoption-changes-p256dh", "adoption-changes-auth",
      "adoption-changes-credentials",
      "adoption-changes-device", "adoption-changes-instance", "adoption-changes-capabilities",
      "adoption-missing-v3-negotiation", "adoption-negotiation-boolean-is-not-integer",
    )
    assertTrue("canonical adoption mutation vectors are present", mutations.keys.containsAll(requiredRejections))
    for (id in requiredRejections) {
      val mutation = mutations.getValue(id)
      assertEquals(false, mutation["row_mutation"].asBoolean())
      assertEquals(false, mutation["outbox_mutation"].asBoolean())
      assertEquals(mutation["expected_error"], mutation["expected_response"]["error"])
    }

    val floorCases = cases["legacy_floor_cases"].associateBy { it["id"].asText() }
    assertEquals("saved_receipt_no_mutation", floorCases.getValue("legacy-known-exact-replay")["expected"].asText())
    assertEquals("epoch_conflict", floorCases.getValue("legacy-fresh-state-identical-request")["expected_error"].asText())
    assertEquals("epoch_conflict", cases["legacy_unkeyed_same_epoch_case"]["expected_error"].asText())

    val accounts = cases["account_selection_cases"].associateBy { it["id"].asText() }
    val independentAccount = accounts.getValue("independent-account-b-epoch1-create")
    assertEquals("selected_account_only", independentAccount["row_comparisons"].asText())
    assertEquals(listOf("account_id", "request_id"), independentAccount["receipt_lookup_scope"].map { it.asText() })
    assertEquals(false, independentAccount["server_cross_account_key_guard"].asBoolean())
    assertEquals(true, independentAccount["client_requires_fresh_control_key_for_new_registration"].asBoolean())
    assertEquals(true, independentAccount["legacy_a_unchanged"].asBoolean())
    assertEquals("create_b", independentAccount["expected"].asText())

    val absentHigherEpoch = accounts.getValue("absent-account-b-epoch-above-one-rejected")
    assertEquals("epoch_conflict", absentHigherEpoch["expected_error"].asText())
    for (field in listOf("row_mutation", "generation_mutation", "queue_mutation", "receipt_ledger_mutation")) {
      assertEquals("absent account B remains unchanged: $field", false, absentHigherEpoch[field].asBoolean())
    }

    val precedence = cases["validation_precedence_cases"].single()
    assertEquals(listOf("supported_event_versions", "capabilities"), precedence["validation_order"].map { it.asText() })
    assertEquals("unsupported_version", precedence["expected_error"].asText())
  }

  @Test
  fun `v3 replay vectors distinguish historical receipt from unseen stale import`() {
    val cases = json("/colliesocket-contract-v3/fixtures/runtime-cases-v3.json")["cases"].associateBy { it["id"].asText() }

    val recorded = cases.getValue("old-file-recorded-reimport-after-newer-same-epoch")
    assertEquals("saved_historical_receipt", recorded["expected"].asText())
    assertEquals("recorded_exact", recorded["receipt_state"].asText())
    assertEquals(false, recorded["historical_receipt_is_current_confirmation"].asBoolean())
    assertEquals(false, recorded["row_mutation"].asBoolean())
    assertEquals(false, recorded["queue_mutation"].asBoolean())

    val unseen = cases.getValue("old-file-unseen-reimport-after-newer-same-epoch")
    assertEquals("reject", unseen["expected"].asText())
    assertEquals("unseen", unseen["receipt_state"].asText())
    assertEquals("epoch_conflict", unseen["expected_error"].asText())
    assertEquals(false, unseen["row_mutation"].asBoolean())
    assertEquals(false, unseen["queue_mutation"].asBoolean())

    val request = json("/colliesocket-contract-v3/fixtures/enrollment-historical-request-v3.json")
    val response = json("/colliesocket-contract-v3/fixtures/response-historical-v3-replay.json")
    assertEquals(request["request_id"], response["request_id"])
    assertEquals(request["subscription"]["subscription_epoch"], response["subscription_epoch"])
    assertEquals(request["subscription"]["instance"], response["instance"])
    assertEquals("accepted", response["status"].asText())
    assertTrue(response["replayed"].asBoolean())
  }

  @Test
  fun `missing v3 capabilities produce invalid enrollment even with unsupported versions`() {
    val cases = json("/colliesocket-contract-v3/fixtures/invalid-cases-v3.json")["public_error_cases"]
    assertEquals(2, cases.size())
    for (case in cases) {
      assertEquals("invalid_enrollment", case["expected_error"].asText())
      val enrollment = json("/colliesocket-contract-v3/fixtures/${case["fixture"].asText()}")
      assertNull(enrollment["subscription"]["capabilities"])
    }
  }
}
