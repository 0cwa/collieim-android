def fail(message):
    print(f"error: {message}", file=sys.stderr)
    sys.exit(1)


def load_spec():
    spec = json.loads(SPEC.read_text())
    if spec.get("schema") != 1:
        fail(f"{SPEC}: unsupported schema {spec.get('schema')!r}")
    seen_ids = set()
    seen_names = set()
    for palette in spec["palettes"]:
        if set(palette) != {"id", "style_name", "seed", "scheme", "contrast"}:
            fail(f"palette fields must be id, style_name, seed, scheme and contrast: {palette}")
        if not re.fullmatch(r"[a-z][a-z0-9_]*", palette["id"]) or palette["id"] in RESERVED_IDS:
            fail(f"invalid palette id {palette['id']!r}")
        if not re.fullmatch(r"[A-Z][A-Za-z0-9]*", palette["style_name"]):
            fail(f"invalid style name {palette['style_name']!r}")
        if not re.fullmatch(r"#[0-9A-F]{6}", palette["seed"]):
            fail(f"seed must be #RRGGBB in upper case: {palette['seed']!r}")
        if palette["scheme"] not in SCHEMES:
            fail(f"scheme must be one of {', '.join(SCHEMES)}: {palette['scheme']!r}")
        if not isinstance(palette["contrast"], (int, float)) or not -1.0 <= palette["contrast"] <= 1.0:
            fail(f"contrast must be between -1 and 1: {palette['contrast']!r}")
        if palette["id"] in seen_ids or palette["style_name"] in seen_names:
            fail(f"duplicate palette {palette['id']}")
        seen_ids.add(palette["id"])
        seen_names.add(palette["style_name"])
    return spec


def pinned_material_version():
    text = (ROOT / "gradle/libs.versions.toml").read_text()
    match = re.search(r'^material-material = "com\.google\.android\.material:material:([^"]+)"', text, re.M)
    if not match:
        fail("could not find material-material in gradle/libs.versions.toml")
    return match.group(1)


def pinned_aar_sha256(version):
    text = (ROOT / "gradle/verification-metadata.xml").read_text()
    pattern = (
        r'<component group="com\.google\.android\.material" name="material" version="' + re.escape(version) + r'">'
        r'\s*<artifact name="material-' + re.escape(version) + r'\.aar">\s*<sha256 value="([0-9a-f]{64})"'
    )
    match = re.search(pattern, text)
    if not match:
        fail(f"no verification-metadata entry for material-{version}.aar")
    return match.group(1)


def find_aar(args, version, work):
    if args.aar:
        return Path(args.aar)
    cache = Path(os.environ.get("GRADLE_USER_HOME", Path.home() / ".gradle")) / "caches/modules-2/files-2.1"
    candidates = sorted(cache.glob(f"com.google.android.material/material/{version}/*/material-{version}.aar"))
    if candidates:
        return candidates[0]
    if not args.download:
        fail(f"material-{version}.aar is not in the Gradle cache; pass --aar PATH or --download")
    url = f"https://dl.google.com/dl/android/maven2/com/google/android/material/material/{version}/material-{version}.aar"
    target = work / f"material-{version}.aar"
    print(f"Downloading {url}", file=sys.stderr)
    with urllib.request.urlopen(url) as response, open(target, "wb") as out:
        shutil.copyfileobj(response, out)
    return target


def role_values(classes_jar, palette, brightness):
    java = shutil.which("java", path=os.path.join(os.environ["JAVA_HOME"], "bin")) if os.environ.get("JAVA_HOME") else None
    java = java or shutil.which("java")
    if not java:
        fail("java 17 or newer is required")
    result = subprocess.run(
        [java, "-cp", str(classes_jar), str(ROLES_TOOL), palette["seed"], palette["scheme"], brightness, repr(float(palette["contrast"]))],
        text=True,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
    )
    if result.returncode != 0:
        fail(f"PaletteRoles failed:\n{result.stderr}")
    values = {}
    for line in result.stdout.splitlines():
        role, value = line.split("=")
        values[role] = value
    expected = [role for role, _, _ in ROLES]
    if list(values) != expected:
        fail(f"PaletteRoles returned {list(values)}, expected {expected}")
    for role, value in values.items():
        if not re.fullmatch(r"#FF[0-9A-F]{6}", value):
            fail(f"{palette['id']} {brightness} {role} is not an opaque color: {value}")
    return values


def luminance(value):
    channels = []
    for i in (3, 5, 7):
        c = int(value[i:i + 2], 16) / 255
        channels.append(c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4)
    return 0.2126 * channels[0] + 0.7152 * channels[1] + 0.0722 * channels[2]


def contrast_ratio(a, b):
    la, lb = sorted((luminance(a), luminance(b)), reverse=True)
    return (la + 0.05) / (lb + 0.05)


def check_contrast(palette, brightness, values):
    for foreground, background in CONTRAST_PAIRS:
        ratio = contrast_ratio(values[foreground], values[background])
        if ratio < 4.5:
            fail(f"{palette['id']} {brightness}: {foreground} on {background} is {ratio:.2f}:1, below 4.5:1")


def color_name(palette, brightness, role):
    snake = re.sub(r"([A-Z])", r"_\1", role).lower()
    return f"user_palette_{palette['id']}_{brightness}_{snake}"


def render_xml(palettes):
    lines = ['<?xml version="1.0" encoding="utf-8"?>', f"<!-- {HEADER} -->", '<resources xmlns:tools="http://schemas.android.com/tools">']
    for palette, roles in palettes:
        lines.append("")
        lines.append(f"    <!-- {palette['id']}: seed {palette['seed']}, {palette['scheme']}, contrast {float(palette['contrast'])} -->")
        for brightness in ("light", "dark"):
            for role, _, _ in ROLES:
                lines.append(f'    <color name="{color_name(palette, brightness, role)}" tools:ignore="UnusedResources">{roles[brightness][role]}</color>')
        for brightness in ("light", "dark"):
            lines.append("")
            lines.append(f'    <style name="ThemeOverlay.Collie.Palette.{palette["style_name"]}.{brightness.capitalize()}" parent="">')
            lines.append(f'        <item name="collie_palette">{palette["id"]}</item>')
            for role, attrs, _ in ROLES:
                for attr in attrs:
                    lines.append(f'        <item name="{attr}">@color/{color_name(palette, brightness, role)}</item>')
            for attr, light, dark in APP_BINDINGS:
                lines.append(f'        <item name="{attr}">{light if brightness == "light" else dark}</item>')
            lines.append("    </style>")
    lines.append("</resources>")
    return "\n".join(lines) + "\n"


def render_overlays(palettes):
    lines = [
        f"// {HEADER}",
        "",
        "package org.thoughtcrime.securesms.util",
        "",
        "import androidx.annotation.StyleRes",
        "import org.thoughtcrime.securesms.R",
        "",
        "/** Roles-only theme overlays for the built-in palettes, applied after an Activity's own style. */",
        "object GeneratedPaletteOverlays {",
        "",
        "  /** Stable palette IDs, as stored in preferences and backups. */",
        "  @JvmField",
        "  val IDS: List<String> = listOf(" + ", ".join(f'"{p["id"]}"' for p, _ in palettes) + ")",
        "",
        "  /** The overlay for [id] at the given brightness, or 0 for an unknown ID. */",
        "  @JvmStatic",
        "  @StyleRes",
        "  fun overlay(id: String?, dark: Boolean): Int {",
        "    return when (id) {",
    ]
    for palette, _ in palettes:
        style = f"R.style.ThemeOverlay_Collie_Palette_{palette['style_name']}"
        lines.append(f'      "{palette["id"]}" -> if (dark) {style}_Dark else {style}_Light')
    lines += ["      else -> 0", "    }", "  }", "}"]
    return "\n".join(lines) + "\n"


def kotlin_color(value):
    return f"Color(0x{value[1:]})"


def render_compose(palettes):
    lines = [
        f"// {HEADER}",
        "",
        "package org.signal.core.ui.compose.theme",
        "",
        "import androidx.compose.material3.darkColorScheme",
        "import androidx.compose.material3.lightColorScheme",
        "import androidx.compose.ui.graphics.Color",
        "",
        "internal object GeneratedUserPalettes {",
    ]
    for palette, roles in palettes:
        constant = re.sub(r"(?<!^)([A-Z])", r"_\1", palette["style_name"]).upper()
        lines.append("")
        lines.append(f"  val {constant} = UserPalette(")
        lines.append(f'    id = "{palette["id"]}",')
        lines.append(f"    seed = {kotlin_color('#FF' + palette['seed'][1:])},")
        lines.append(f'    scheme = "{palette["scheme"]}",')
        for brightness in ("light", "dark"):
            lines.append(f"    {brightness} = {brightness}ColorScheme(")
            for role, _, compose in ROLES:
                if compose:
                    lines.append(f"      {compose} = {kotlin_color(roles[brightness][role])},")
            lines.append("    ),")
        for brightness in ("light", "dark"):
            swatch = ", ".join(kotlin_color(roles[brightness][r]) for r in ("primary", "secondaryContainer", "tertiary", "surface"))
            lines.append(f"    {brightness}Swatch = listOf({swatch}),")
        lines.append("  )")
    names = ", ".join(re.sub(r"(?<!^)([A-Z])", r"_\1", p["style_name"]).upper() for p, _ in palettes)
    lines += ["", f"  val ALL: List<UserPalette> = listOf({names})", "}"]
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--aar", help="path to the pinned Material Components AAR")
    parser.add_argument("--download", action="store_true", help="download the pinned AAR when it is not cached")
    parser.add_argument("--check", action="store_true", help="fail if the checked-in output differs")
    args = parser.parse_args()

    spec = load_spec()
    version = pinned_material_version()
    if spec["material"] != f"com.google.android.material:material:{version}":
        fail(f"{SPEC} names {spec['material']}, but the app pins material {version}; regenerate deliberately")
    expected_sha = pinned_aar_sha256(version)

    with tempfile.TemporaryDirectory() as tmp:
        work = Path(tmp)
        aar = find_aar(args, version, work)
        actual_sha = hashlib.sha256(aar.read_bytes()).hexdigest()
        if actual_sha != expected_sha:
            fail(f"{aar} has SHA-256 {actual_sha}, expected {expected_sha} from gradle/verification-metadata.xml")
        classes_jar = work / "classes.jar"
        with zipfile.ZipFile(aar) as archive:
            classes_jar.write_bytes(archive.read("classes.jar"))

        palettes = []
        for palette in spec["palettes"]:
            roles = {}
            for brightness in ("light", "dark"):
                roles[brightness] = role_values(classes_jar, palette, brightness)
                check_contrast(palette, brightness, roles[brightness])
            palettes.append((palette, roles))

    rendered = {
        XML_OUT: render_xml(palettes),
        OVERLAYS_OUT: render_overlays(palettes),
        COMPOSE_OUT: render_compose(palettes),
    }

    if args.check:
        stale = [path for path, text in rendered.items() if not path.exists() or path.read_text() != text]
        for path in stale:
            print(f"DRIFT: {path.relative_to(ROOT)}", file=sys.stderr)
        if stale:
            print("Run python3 tooling/user-theming/generate.py to regenerate.", file=sys.stderr)
            sys.exit(1)
        print(f"Palettes match material {version} (AAR SHA-256 {actual_sha}).")
        return

    for path, text in rendered.items():
        path.write_text(text)
        print(f"Wrote {path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
